import shutil

import torch
import os
import sys
import logging
import copy
import hydra
import numpy as np
from pathlib import Path
from omegaconf import DictConfig, OmegaConf

sys.path.append("/home/lyp/Code/DiffuseGAE")
from torch.utils.data import DataLoader
from torchvision.utils import save_image
from main.models.diffusion import DDPM, Encoder, SuperResModel, make_sampler
from main.models.autoencoders import GAE_PL
from main.models.joint_model import ModelWrapper
from main.datasets.eval import ImageDataset
from main.util import configure_device, parse_str, linear_interpolation, sphere_interpolation, get_dataset
from lightning_fabric.utilities.seed import seed_everything
from tqdm import tqdm

logger = logging.getLogger(__name__)
logger.setLevel(logging.DEBUG)


@hydra.main(config_path='../configs', config_name='default_conf.yaml')
def interpolation(config):
    logger.info(OmegaConf.to_yaml(config))
    config_joint = config.dataset.joint
    config_GAE = config.dataset.GAE
    # model_wrapper should have encoder+GAE+ddpm

    # Set seed
    seed_everything(config_joint.evaluation.seed)

    # Dataset
    # folder should be absolute path
    folder = config_joint.data.imgs_root
    assert Path(folder).is_absolute()
    z_norm = config_GAE.data.norm
    z_root = config_GAE.data.root  # latent data root for getting z_mean and z_std

    dev_ = configure_device(config_joint.evaluation.device)
    dev = dev_[1] if isinstance(dev_, tuple) else dev_

    dev = torch.device(f'cuda:{dev[0]}' if isinstance(dev, list) else dev)
    d_type = config_joint.data.name
    image_size = config_joint.data.image_size
    if 'ilab' in d_type:
        attr = ['id', 'back', 'pose']
        attr_num = len(attr)
        dim_separator = [slice(0, 60),
                         slice(60, 80),
                         slice(80, 100)]

    elif 'fonts' in d_type:
        # todo change
        attr = ['content', 'size', 'font_color', 'back_color', 'style']
        attr_num = len(attr)
        dim_separator = []
        for i in range(0, 100, 20):
            dim_separator.append(slice(i, i + 20))
    else:
        raise NotImplementedError()

    dataset = ImageDataset(
        folder=folder,
        image_size=config_joint.data.image_size,
        exts=['jpg', 'png'],
        do_augment=False,
    )

    if z_norm:
        z_mean = get_dataset(config_GAE.data.name, z_root, image_size, norm=z_norm, flip=False).z_mean.to(dev)
        z_std = get_dataset(config_GAE.data.name, z_root, image_size, norm=z_norm, flip=False).z_std.to(dev)
    # Model
    # eps predictor
    attn_resolutions = parse_str(config_joint.model_ddpm.attn_resolutions)
    dim_mults = parse_str(config_joint.model_ddpm.dim_mults)
    decoder = SuperResModel(
        in_channels=config_joint.data.n_channels,
        model_channels=config_joint.model_ddpm.dim,
        out_channels=3,
        emb_channels=config_joint.model_ddpm.emb_channels,  # t_emb and z_emb(generated by AE)
        num_res_blocks=config_joint.model_ddpm.n_residual,
        attention_resolutions=attn_resolutions,
        channel_mult=dim_mults,
        use_checkpoint=False,
        dropout=config_joint.model_ddpm.dropout,
        num_heads=config_joint.model_ddpm.n_heads,
        z_dim=config_joint.evaluation.z_dim,
        use_scale_shift_norm=config_joint.model_ddpm.use_scale_shift_norm,
        use_z=config_joint.model_ddpm.use_z,
        use_x_hat=config_joint.model_ddpm.use_x_hat,
        use_mappingnet=config_joint.model_ddpm.use_mappingnet
    )
    ema_decoder = copy.deepcopy(decoder)
    decoder.eval()
    ema_decoder.eval()

    # base sampler(DDPM) settings
    online_ddpm = DDPM(
        decoder,
        beta_1=config_joint.model_ddpm.beta1,
        beta_2=config_joint.model_ddpm.beta2,
        T=config_joint.model_ddpm.n_timesteps,
        var_type=config_joint.evaluation.variance,
    )
    target_ddpm = DDPM(
        ema_decoder,
        beta_1=config_joint.model_ddpm.beta1,
        beta_2=config_joint.model_ddpm.beta2,
        T=config_joint.model_ddpm.n_timesteps,
        var_type=config_joint.evaluation.variance,
    )

    # Encoder settings
    config_model_encoder = config_joint.model_Encoder
    attention_resolutions = parse_str(config_model_encoder.attention_resolutions)
    channel_mult = parse_str(config_model_encoder.channel_mult)
    encoder = Encoder(
        in_channels=config_model_encoder.in_channels,
        model_channels=config_model_encoder.model_channels,
        out_channels=config_model_encoder.out_channels,
        num_res_blocks=config_model_encoder.num_res_blocks,
        attention_resolutions=attention_resolutions,
        dropout=config_model_encoder.dropout,
        channel_mult=channel_mult,
        conv_resample=config_model_encoder.conv_resample,
        use_checkpoint=config_model_encoder.use_checkpoint,
        num_heads=config_model_encoder.num_heads,
        resblock_updown=config_model_encoder.resblock_updown
    )

    # GAE settings
    # Gae_pl = GAE_PL(config_GAE)
    # todo delete
    Gae_pl = GAE_PL.load_from_checkpoint(config_GAE.model.ckpt_path, strict=False).to(dev)

    # get joint_model with models mentioned above from ckpt
    joint_model = ModelWrapper.load_from_checkpoint(
        config_joint.evaluation.ckpt_path,
        strict=True,
        online_network=online_ddpm,
        target_network=target_ddpm,
        encoder=encoder,
        Gae_pl=Gae_pl,
    )
    joint_model.eval()
    joint_model.to(dev)
    encoder = joint_model.encoder

    # both ddpm and ddim can use it
    eps_predictor = joint_model.base_sampler.decoder  # from online or target

    T_encode_reversed, T_pred_steps = config_joint.evaluation.T_encode_reversed, config_joint.evaluation.pred_steps
    # use bigger T for ddim_reversed_sample
    ddim_sampler = make_sampler(eps_predictor, T_pred_steps).to(dev)
    ddim_reversed_sampler = make_sampler(eps_predictor, T_encode_reversed).to(dev)

    # start interpolation
    loader = DataLoader(
        dataset=dataset,
        batch_size=2,
        num_workers=2,
        shuffle=False,
        pin_memory=True,
        drop_last=True,
    )

    num_intp = config_joint.evaluation.num_intp
    alpha = torch.linspace(0, 1, num_intp, dtype=torch.float32, device=dev)
    with torch.no_grad():
        with tqdm(loader, total=len(dataset)) as pbar:
            for idx, pair in enumerate(loader):
                if idx != 6: continue
                logger.info(f'group {idx + 1}')
                # idx is which attr_idx we want to interpolate.
                # get z_dis and x_T for interpolation, linear for z_dis and sphere for x_T
                pair = pair.to(dev)
                z_original = encoder(pair)
                z_in_Gae_pl = (z_original - z_mean) / z_std if z_norm else z_original
                z_dis = Gae_pl.get_latent_code(z_in_Gae_pl)
                logger.info('Sampling x_T')
                # if idx >= 4:
                x_T = ddim_reversed_sampler.ddim_reverse_sample_loop(
                    x=pair,
                    cond=None,
                    z=z_original,
                )['sample']
                logger.info('Sampling x_T done')
                # interpolate between x_Ts
                intp_x = sphere_interpolation(x_T[0], x_T[1], alpha)
                # intp_x = torch.randn((num_intp, 3, 128, 128)).to(dev)

                # interpolate between z_dis
                l_z, r_z = z_dis[0], z_dis[1]
                if 'ilab' in d_type:
                    if idx <= 2:
                        intp_z_each_attr = []
                        for i in range(attr_num):
                            intp_z_each_attr.append(
                                linear_interpolation(l_z[dim_separator[i]], r_z[dim_separator[i]], alpha) if i == idx
                                else ((l_z[dim_separator[i]] + r_z[dim_separator[i]]) / 2)[None, :].expand(num_intp, -1)
                            )
                        intp_z = Gae_pl.get_recon(torch.cat(intp_z_each_attr, dim=-1))
                        # intp_z = Gae_pl.get_recon(z_dis)  # todo
                        intp_z = intp_z * z_std + z_mean if z_norm else intp_z
                        # intp_z = linear_interpolation(intp_z[0], intp_z[1], alpha)  # todo
                        logger.info('We got intp_z!')

                    elif idx > 6:
                        # 4 groups in total
                        # intp_z_dis = linear_interpolation(l_z, r_z, alpha)
                        intp_z_each_attr = []
                        for i in range(attr_num):
                            if i == 1:
                                intp_z_each_attr.append(((l_z[dim_separator[i]] + r_z[dim_separator[i]]) / 2)[None, :].expand(num_intp, -1))
                            else:
                                intp_z_each_attr.append(linear_interpolation(l_z[dim_separator[i]], r_z[dim_separator[i]], alpha))

                        intp_z = Gae_pl.get_recon(torch.cat(intp_z_each_attr, dim=-1))
                        intp_z = intp_z * z_std + z_mean if z_norm else intp_z

                        # intp_z = Gae_pl.get_recon(z_dis)  # todo
                        # intp_z = intp_z * z_std + z_mean if z_norm else intp_z  # todo
                        # intp_z = linear_interpolation(intp_z[0], intp_z[1], alpha)  # todo

                        logger.info('We got intp_z!')

                    else:
                        # 4 groups in total
                        intp_z_dis = linear_interpolation(l_z, r_z, alpha)
                        intp_z = Gae_pl.get_recon(intp_z_dis)
                        intp_z = intp_z * z_std + z_mean if z_norm else intp_z

                        # intp_z = Gae_pl.get_recon(z_dis)  # todo
                        # intp_z = intp_z * z_std + z_mean if z_norm else intp_z  # todo
                        # intp_z = linear_interpolation(intp_z[0], intp_z[1], alpha)  # todo
                        logger.info('We got intp_z!')

                elif 'fonts' in d_type:
                    intp_z_each_attr = []
                    if idx < 5:
                        for i in range(attr_num):
                            intp_z_each_attr.append(
                                linear_interpolation(l_z[dim_separator[i]], r_z[dim_separator[i]], alpha) if i == idx
                                else ((l_z[dim_separator[i]] + r_z[dim_separator[i]]) / 2)[None, :].expand(num_intp, -1)
                            )
                        intp_z = Gae_pl.get_recon(torch.cat(intp_z_each_attr, dim=-1))
                        # intp_z = Gae_pl.get_recon(z_dis)  # todo
                        intp_z = intp_z * z_std + z_mean if z_norm else intp_z
                        # intp_z = linear_interpolation(intp_z[0], intp_z[1], alpha)  # todo

                    elif idx < 10:
                        attr1_i, attr2_i = idx % 5, (idx % 5 + 1) % 5
                        for i in range(attr_num):
                            intp_z_each_attr.append(
                                linear_interpolation(l_z[dim_separator[i]], r_z[dim_separator[i]], alpha) if i == attr1_i or i == attr2_i
                                else ((l_z[dim_separator[i]] + r_z[dim_separator[i]]) / 2)[None, :].expand(num_intp, -1)
                            )
                        intp_z = Gae_pl.get_recon(torch.cat(intp_z_each_attr, dim=-1))
                        intp_z = intp_z * z_std + z_mean if z_norm else intp_z
                    else:
                        raise NotImplementedError('idx overflow')
                    logger.info('We got intp_z!')
                else:
                    raise NotImplementedError(f'{d_type} does not exist')

                # interpolate between images
                intp_imgs = ddim_sampler.ddim_sample(
                    x_t=intp_x,
                    cond=None,
                    z=intp_z,
                    eta=0.0,
                )[str(config_joint.evaluation.pred_steps)]

                intp_imgs = ((intp_imgs + 1) / 2).cpu()
                save_image(intp_imgs, os.path.join(folder, f'group{idx + 1}', 'interpolation.png'), nrow=num_intp)
                logger.info(f'We got intp_img in group{idx + 1}!')

                pbar.update(2)


if __name__ == '__main__':
    interpolation()
