@torch.no_grad()
def save_images_for_evaluation(original_batch: torch.Tensor,
                               recon_batch: torch.Tensor,
                               save_path,
                               start_index):
    original_savepath = os.path.join(save_path, 'original')
    recon_savepath = os.path.join(save_path, 'recon')
    if not os.path.exists(original_savepath) or not os.path.exists(recon_savepath):
        os.makedirs(original_savepath)
        os.makedirs(recon_savepath)
    batch_size = original_batch.shape[0]
    for idx in range(batch_size):
        save_image(original_batch[idx], os.path.join(original_savepath, f'{idx + start_index}'.zfill(5) + '.png'), format='png')
        save_image(recon_batch[idx], os.path.join(recon_savepath, f'{idx + start_index}'.zfill(5) + '.png'), format='png')


# modify default_conf.yaml for different dataset or use dataset=/path/to/dataset_eval_yaml/ in cli
@hydra.main(config_path="../configs", config_name="default_conf")
def generate_recons(config):
    logger.info(OmegaConf.to_yaml(config, resolve=True))
    config_joint = config.dataset.joint
    config_GAE = config.dataset.GAE

    # Setting seed
    seed_everything(config_joint.evaluation.seed)

    # Dataset
    root = config_joint.data.root  # evaluation dataset root
    z_root = config_GAE.data.root  # latent data root
    z_norm = config_GAE.data.norm
    dev_ = configure_device(config_joint.evaluation.device)
    dev = torch.device(f'cuda:{dev_[1][0]}') if isinstance(dev_, tuple) else torch.device(dev_)

    d_type = config_joint.data.name

    # dim_slice = []
    # if 'ilab' in d_type:
    #     attr = ['id', 'background', 'pose']
    #     attr_num = len(attr)
    #     dim_slice = [slice(0, 60),
    #                  slice(60, 80),
    #                  slice(80, 100)]
    # elif 'fonts' in d_type:
    #     # todo change
    #     for i in range(0, 100, 20):
    #         dim_slice.append(slice(i, i + 20))
    # else:
    #     raise NotImplementedError()

    # group_dataset in default
    is_group_dataset = config_joint.data.is_group_dataset
    group_size = config_joint.data.group_size
    image_size = config_joint.data.image_size
    dataset = get_dataset(
        d_type, root, image_size, norm=config_joint.data.norm, flip=config_joint.data.hflip
    )
    if z_norm:
        z_mean = get_dataset(config_GAE.data.name, z_root, config_GAE.data.image_size, norm=z_norm, flip=False).z_mean
        z_std = get_dataset(config_GAE.data.name, z_root, config_GAE.data.image_size, norm=z_norm, flip=False).z_std
    N = len(dataset)
    batch_size = min(N, config_joint.evaluation.batch_size)

    # Model
    # eps predictor
    attn_resolutions = parse_str(config_joint.model_ddpm.attn_resolutions)
    dim_mults = parse_str(config_joint.model_ddpm.dim_mults)
    decoder = SuperResModel(
        in_channels=config_joint.data.n_channels,
        model_channels=config_joint.model_ddpm.dim,
        out_channels=3,
        emb_channels=config_joint.model_ddpm.emb_channels,  # t_emb and z_emb(generated by AE)
        num_res_blocks=config_joint.model_ddpm.n_residual,
        attention_resolutions=attn_resolutions,
        channel_mult=dim_mults,
        use_checkpoint=False,
        dropout=config_joint.model_ddpm.dropout,
        num_heads=config_joint.model_ddpm.n_heads,
        z_dim=config_joint.evaluation.z_dim,
        use_scale_shift_norm=config_joint.model_ddpm.use_scale_shift_norm,
        use_z=config_joint.model_ddpm.use_z,
        use_x_hat=config_joint.model_ddpm.use_x_hat,
        use_mappingnet=config_joint.model_ddpm.use_mappingnet
    )
    ema_decoder = copy.deepcopy(decoder)
    decoder.eval()
    ema_decoder.eval()

    # base sampler(DDPM) settings
    online_ddpm = DDPM(
        decoder,
        beta_1=config_joint.model_ddpm.beta1,
        beta_2=config_joint.model_ddpm.beta2,
        T=config_joint.model_ddpm.n_timesteps,
        var_type=config_joint.evaluation.variance,
    )
    target_ddpm = DDPM(
        ema_decoder,
        beta_1=config_joint.model_ddpm.beta1,
        beta_2=config_joint.model_ddpm.beta2,
        T=config_joint.model_ddpm.n_timesteps,
        var_type=config_joint.evaluation.variance,
    )

    # Encoder settings
    config_model_encoder = config_joint.model_Encoder
    attention_resolutions = parse_str(config_model_encoder.attention_resolutions)
    channel_mult = parse_str(config_model_encoder.channel_mult)
    encoder = Encoder(
        in_channels=config_model_encoder.in_channels,
        model_channels=config_model_encoder.model_channels,
        out_channels=config_model_encoder.out_channels,
        num_res_blocks=config_model_encoder.num_res_blocks,
        attention_resolutions=attention_resolutions,
        dropout=config_model_encoder.dropout,
        channel_mult=channel_mult,
        conv_resample=config_model_encoder.conv_resample,
        use_checkpoint=config_model_encoder.use_checkpoint,
        num_heads=config_model_encoder.num_heads,
        resblock_updown=config_model_encoder.resblock_updown
    )

    # # GAE settings
    # Gae_pl = GAE_PL(config_GAE)
    # todo delete
    Gae_pl = GAE_PL.load_from_checkpoint(config_GAE.model.ckpt_path, strict=False).to(dev)

    # get joint_model with models mentioned above from ckpt
    joint_model = ModelWrapper.load_from_checkpoint(
        config_joint.evaluation.ckpt_path,
        strict=True,
        online_network=online_ddpm,
        target_network=target_ddpm,
        encoder=encoder,
        Gae_pl=Gae_pl,
    )
    joint_model.eval()
    joint_model.to(dev)
    encoder = joint_model.encoder
    # both ddpm and ddim can use it
    eps_predictor = joint_model.base_sampler.decoder

    T_encode_reversed, T_pred_steps = config_joint.evaluation.T_encode_reversed, config_joint.evaluation.pred_steps
    # use bigger T for ddim_reversed_sample
    ddim_sampler = make_sampler(eps_predictor, T_pred_steps).to(dev)
    ddim_reversed_sampler = make_sampler(eps_predictor, T_encode_reversed).to(dev)

    # loader settings
    loader = DataLoader(
        dataset,
        batch_size,
        num_workers=config_joint.evaluation.workers,
        pin_memory=True,
        shuffle=True,
        drop_last=True,
    )
    # Sample settings
    recon_model = config_joint.evaluation.recon_model
    recon_mode = config_joint.evaluation.recon_mode
    recon_save_path = config_joint.evaluation.recon_save_path
    if not os.path.exists(recon_save_path):
        os.makedirs(recon_save_path)
    if not os.path.exists(os.path.join(recon_save_path, f'step_{T_pred_steps}')):
        os.makedirs(os.path.join(recon_save_path, f'step_{T_pred_steps}'))
    num_samples = config_joint.evaluation.num_samples

    total = 0
    with tqdm(total=num_samples) as pbar:
        with torch.no_grad():
            for idx, batch in enumerate(loader):
                batch = batch.to(dev)
                batch = batch.flatten(0, 1) if is_group_dataset else batch
                z = encoder(batch)
                if recon_model == 'gae_out':
                    if z_norm:
                        z_mean, z_std = z_mean.to(z.device), z_std.to(z.device)
                        z = (z - z_mean) / z_std
                        z_recon, _ = Gae_pl(z)
                        z_recon = z_recon * z_std + z_mean
                    else:
                        z_recon = Gae_pl(z)
                z_in_ddim = z_recon if recon_model == 'gae_out' else z
                # To reconstruct original images, we need the deterministic noise sampled from original images in deterministic ODE
                x_t = ddim_reversed_sampler.ddim_reverse_sample_loop(
                    x=batch,
                    cond=None,
                    z=z_in_ddim,
                    clip_denoised=True,
                    eta=0.,
                )['sample'] if recon_mode == 'step' else torch.randn_like(batch, device=dev)

                # torch.save(x_t, os.path.join(recon_save_path, f'step_{T_pred_steps}', f'reversed_xt_batch_{idx}.pkl'))
                x_recon = ddim_sampler.ddim_sample(
                    x_t=x_t,
                    cond=None,
                    z=z_in_ddim,
                    eta=0.,
                    guidance_weight=0.,
                )[str(T_pred_steps)]

                batch = (batch + 1) / 2
                x_recon = (x_recon + 1) / 2
                if is_group_dataset:
                    save_image(batch, os.path.join(recon_save_path, f'batch_{idx + 1}-original.png'), format='png', nrow=group_size)
                    save_image(x_recon, os.path.join(recon_save_path, f'batch_{idx + 1}-reconstructed.png'), format='png', nrow=group_size)
                else:
                    save_images_for_evaluation(batch, x_recon, save_path=os.path.join(recon_save_path, f'{recon_mode}_{T_pred_steps}'), start_index=total + 1)
                total += batch_size
                pbar.update(batch_size)
                if total >= num_samples:
                    break


if __name__ == "__main__":
    generate_recons()
