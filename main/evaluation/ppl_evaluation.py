class WrapVGG16(nn.Module):
    def __init__(self, pkl_path):
        super().__init__()
        with open(pkl_path, 'rb') as f:
            vgg16 = pickle.load(f)
        self.vgg16 = copy.deepcopy(vgg16)

    def forward(self, *args, **kwargs):
        return self.vgg16(*args, **kwargs)


@hydra.main(config_path="../configs", config_name="default_conf.yaml")
def evaluate_ppl(config):
    logger.info(OmegaConf.to_yaml(config))
    config_joint = config.dataset.joint
    config_GAE = config.dataset.GAE
    config_GSL = config.dataset.GSL
    # Set seed
    seed_everything(config_joint.evaluation.seed)
    # extra settings
    eval_model = config_joint.evaluation.ppl_evaluation_model
    eval_mode = config_joint.evaluation.ppl_evaluation_mode
    # Dataset
    # folder should be absolute path
    folder1 = config_joint.data.ppl_imgs_root0
    folder2 = config_joint.data.ppl_imgs_root1
    assert Path(folder1).is_absolute()
    assert Path(folder2).is_absolute()

    dev_ = configure_device(config_joint.evaluation.device)
    dev = dev_[1] if isinstance(dev_, tuple) else dev_

    dev = torch.device(f'cuda:{dev[0]}' if isinstance(dev, list) else dev)
    d_type = config_joint.data.name
    image_size = config_joint.data.image_size
    dataset = DoubleImageDataset(
        folder1=folder1,
        folder2=folder2,
        image_size=config_joint.data.image_size,
        exts=['png'],
        do_augment=False,
    )

    z_norm = config_GAE.data.norm
    z_root = config_GAE.data.root  # latent data root for getting z_mean and z_std
    if z_norm:
        z_mean = get_dataset(config_GAE.data.name, z_root, image_size, norm=z_norm, flip=False).z_mean.to(dev)
        z_std = get_dataset(config_GAE.data.name, z_root, image_size, norm=z_norm, flip=False).z_std.to(dev)

    # Model
    # eps predictor
    attn_resolutions = parse_str(config_joint.model_ddpm.attn_resolutions)
    dim_mults = parse_str(config_joint.model_ddpm.dim_mults)
    decoder = SuperResModel(
        in_channels=config_joint.data.n_channels,
        model_channels=config_joint.model_ddpm.dim,
        out_channels=3,
        emb_channels=config_joint.model_ddpm.emb_channels,  # t_emb and z_emb(generated by AE)
        num_res_blocks=config_joint.model_ddpm.n_residual,
        attention_resolutions=attn_resolutions,
        channel_mult=dim_mults,
        use_checkpoint=False,
        dropout=config_joint.model_ddpm.dropout,
        num_heads=config_joint.model_ddpm.n_heads,
        z_dim=config_joint.evaluation.z_dim,
        use_scale_shift_norm=config_joint.model_ddpm.use_scale_shift_norm,
        use_z=config_joint.model_ddpm.use_z,
        use_x_hat=config_joint.model_ddpm.use_x_hat,
        use_mappingnet=config_joint.model_ddpm.use_mappingnet
    )
    ema_decoder = copy.deepcopy(decoder)
    decoder.eval()
    ema_decoder.eval()
    # base sampler(DDPM) settings
    online_ddpm = DDPM(
        decoder,
        beta_1=config_joint.model_ddpm.beta1,
        beta_2=config_joint.model_ddpm.beta2,
        T=config_joint.model_ddpm.n_timesteps,
        var_type=config_joint.evaluation.variance,
    )
    target_ddpm = DDPM(
        ema_decoder,
        beta_1=config_joint.model_ddpm.beta1,
        beta_2=config_joint.model_ddpm.beta2,
        T=config_joint.model_ddpm.n_timesteps,
        var_type=config_joint.evaluation.variance,
    )
    # Encoder settings
    config_model_encoder = config_joint.model_Encoder
    attention_resolutions = parse_str(config_model_encoder.attention_resolutions)
    channel_mult = parse_str(config_model_encoder.channel_mult)
    encoder = Encoder(
        in_channels=config_model_encoder.in_channels,
        model_channels=config_model_encoder.model_channels,
        out_channels=config_model_encoder.out_channels,
        num_res_blocks=config_model_encoder.num_res_blocks,
        attention_resolutions=attention_resolutions,
        dropout=config_model_encoder.dropout,
        channel_mult=channel_mult,
        conv_resample=config_model_encoder.conv_resample,
        use_checkpoint=config_model_encoder.use_checkpoint,
        num_heads=config_model_encoder.num_heads,
        resblock_updown=config_model_encoder.resblock_updown
    )
    # vgg
    vgg = WrapVGG16(config_joint.evaluation.vgg16_path).to(dev)
    # GAE settings
    # Gae_pl = GAE_PL(config_GAE)
    # todo delete
    logger.info(f"Loading the pretrained models from  {config_GAE.model.ckpt_path}...")
    Gae_pl = GAE_PL.load_from_checkpoint(config_GAE.model.ckpt_path, strict=False).to(dev)
    if 'ilab' in d_type:
        attr = ['id', 'back', 'pose']
        dim_slice = (slice(0, 60),
                     slice(60, 80),
                     slice(80, 100))
    else:
        raise NotImplementedError()
    # get joint_model with models mentioned above from ckpt
    logger.info(f"Loading the pretrained models from  {config_joint.evaluation.ckpt_path}...")
    joint_model = ModelWrapper.load_from_checkpoint(
        config_joint.evaluation.ckpt_path,
        strict=True,
        online_network=online_ddpm,
        target_network=target_ddpm,
        encoder=encoder,
        Gae_pl=Gae_pl,
    )
    model_config = config_GSL.model
    gsl_model = Generator_fc(
        model_config.nc,
        model_config.g_conv_dim,
        model_config.g_repeat_num,
        model_config.z_dim,
    ).to(dev)

    ckpt_path = config_GSL.evaluation.ckpt_path
    if eval_model == 'gsl':
        logger.info(f"Loading the pretrained models from  {ckpt_path}...")
        gsl_model.load_state_dict(torch.load(ckpt_path, map_location=dev))
    joint_model.eval()
    joint_model.to(dev)
    logger.info(f"=> loaded checkpoint done")
    encoder = joint_model.encoder
    # both ddpm and ddim can use it
    eps_predictor = joint_model.base_sampler.decoder
    T_encode_reversed, T_pred_steps = config_joint.evaluation.T_encode_reversed, config_joint.evaluation.pred_steps
    # use bigger T for ddim_reversed_sample
    ddim_sampler = make_sampler(eps_predictor, T_pred_steps).to(dev)
    ddim_reversed_sampler = make_sampler(eps_predictor, T_encode_reversed).to(dev)
    batch_size = config_joint.evaluation.batch_size
    workers = config_joint.evaluation.workers
    loader = DataLoader(
        dataset=dataset,
        batch_size=batch_size,
        num_workers=workers,
        shuffle=False,
        pin_memory=True,
        drop_last=False,
    )
    # i_odd, i_even = get_pair_index(batch_size)

    epsilon = torch.tensor(float(config_joint.evaluation.ppl_epsilon), device=dev)
    use_xT = config_joint.evaluation.use_xT
    all_dist = []

    with torch.no_grad():
        with tqdm(loader, total=len(dataset)) as pbar:
            for idx, batch in enumerate(loader):
                real_bsize = batch['img0'].shape[0]
                img0, img1 = batch['img0'].to(dev), batch['img1'].to(dev)
                alpha = torch.rand([real_bsize], device=dev)[..., None] * (1 if eval_mode == 'full' else 0)
                if eval_model != 'gsl_out':
                    z0_original, z1_original = encoder(img0), encoder(img1)
                    if eval_model == 'encoder_out':
                        z0, z1 = z0_original, z1_original
                        intp_z0 = linear_interpolation(z0, z1, alpha)
                        intp_z1 = linear_interpolation(z0, z1, alpha + epsilon)
                    else:
                        z0_in_Gae_pl = (z0_original - z_mean) / z_std if z_norm else z0_original
                        z1_in_Gae_pl = (z1_original - z_mean) / z_std if z_norm else z1_original
                        z0, z1 = z0_original, z1_original
                        z0_dis = Gae_pl.get_latent_code(z0_in_Gae_pl)
                        z1_dis = Gae_pl.get_latent_code(z1_in_Gae_pl)
                        intp_z0_dis, intp_z1_dis = linear_interpolation(z0_dis, z1_dis, alpha), linear_interpolation(z0_dis, z1_dis, alpha + epsilon)
                        intp_z0, intp_z1 = Gae_pl.get_recon(intp_z0_dis), Gae_pl.get_recon(intp_z1_dis)
                        if z_norm:
                            intp_z0, intp_z1 = intp_z0 * z_std + z_mean, intp_z1 * z_std + z_mean
                    intp_z = torch.cat([intp_z0, intp_z1], dim=0)
                    # get x_T
                    if use_xT:
                        logger.info('Sampling x_T')
                        x_T = ddim_reversed_sampler.ddim_reverse_sample_loop(
                            x=torch.cat((img0, img1), dim=0),
                            cond=None,
                            z=torch.cat((z0, z1), dim=0),
                        )['sample']
                        logger.info('Sampling x_T done')
                        x_T0, x_T1 = x_T[:real_bsize], x_T[real_bsize:]
                        intp_xT0, intp_xT1 = sphere_interpolation(x_T0, x_T1, alpha), sphere_interpolation(x_T0, x_T1, alpha + epsilon)
                        x_T = torch.cat((intp_xT0, intp_xT1), dim=0)
                    else:
                        x_T = torch.cat(
                            (torch.randn_like(img0, device=dev), torch.randn_like(img1, device=dev)),
                            dim=0,
                        )

                    logger.info('Sampling imgs')
                    intp_imgs = ddim_sampler.ddim_sample(
                        x_t=x_T,
                        cond=None,
                        z=intp_z,
                        eta=0.0,
                    )[str(config_joint.evaluation.pred_steps)]
                    logger.info('Sampling imgs done')
                else:
                    z0, z1 = gsl_model.get_latent_code(img0), gsl_model.get_latent_code(img1)
                    intp_z0 = linear_interpolation(z0, z1, alpha)
                    intp_z1 = linear_interpolation(z0, z1, alpha + epsilon)
                    intp_z = torch.cat([intp_z0, intp_z1], dim=0)
                    intp_imgs = gsl_model.recon_from_z(intp_z)
                intp_imgs = (intp_imgs + 1) / 2 * 255  # compute d between first half and last half
                logger.info('calculating distance')
                lpips_t0, lpips_t1 = vgg(img=intp_imgs, resize_images=True, return_lpips=True).chunk(2)
                dist = (lpips_t0 - lpips_t1).square().sum(1) / epsilon ** 2
                logger.info('calculating distance done')
                all_dist.append(dist)
                pbar.update(real_bsize)

        dist = (torch.cat(all_dist)).cpu().numpy()
    lo = np.percentile(dist, 1, interpolation='lower')
    hi = np.percentile(dist, 99, interpolation='higher')
    ppl = np.extract(np.logical_and(dist >= lo, dist <= hi), dist).mean()
    logger.info(f"PPL distance: {ppl}")


if __name__ == '__main__':
    evaluate_ppl()
