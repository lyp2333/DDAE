def get_swapped_zlist_and_recombine_z(batch: torch.Tensor,
                                      encoder: nn.Module,
                                      gae: GAE_PL,
                                      dim_separator,
                                      dtype='ilab',
                                      mean_std=None,
                                      ) -> tuple:
    assert len(batch.shape) == 5, f'batch should have 5 dims'
    batch_size, group_size, *img_attr = batch.shape
    attr_num = group_size - 1
    assert len(dim_separator) == attr_num
    z_batch = encoder(batch.view(batch_size * group_size, *img_attr)).view(batch_size, group_size, -1)
    z_batch = (z_batch - mean_std[0]) / mean_std[1] if mean_std is not None else z_batch
    if 'ilab' in dtype:
        z_list = [z_batch[:, idx, ...] for idx in range(group_size)]
        z_dis_list = [gae.get_latent_code(z) for z in z_list]
        c_z_dis = z_dis_list.pop(2)
        z_combine_dict = {}
        for i in range(group_size - 1):
            # order in z is id back pose, but pose id back in image order
            idx_attr = (i + 2) % attr_num
            z_dis_list[i][:, dim_separator[idx_attr]] = c_z_dis[:, dim_separator[idx_attr]]
            z_combine_dict[f'{idx_attr}'] = z_dis_list[i][:, dim_separator[idx_attr]]
        z_combine = torch.cat([z_combine_dict[str(idx)] for idx in range(attr_num)], dim=1)
        z_dis_recon, recombine_recon = [gae.get_recon(z_dis_list[i]) for i in range(attr_num)], gae.get_recon(z_combine)
    else:
        raise NotImplementedError()
    z_dis_recon, recombine_recon = ([z_dis_recon[i] * mean_std[1] + mean_std[0] for i in range(attr_num)], recombine_recon * mean_std[1] + mean_std[0]) if mean_std is not None \
        else (z_dis_recon, recombine_recon)
    return z_dis_recon, recombine_recon


