def update(i, ax, anim_save_path):
    label = 'timestep {0}'.format(i)
    # 更新直线和x轴（用一个新的x轴的标签）。
    # 用元组（Tuple）的形式返回在这一帧要被重新绘图的物体
    horiAngle = (45 + 3 * i) % 360  # transition(i, 40)
    vertAngle = (45 + 3 * i) % 360  # transition(i, 40)
    print(label, horiAngle, vertAngle)
